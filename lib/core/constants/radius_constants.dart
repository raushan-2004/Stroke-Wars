/// Border radius constants for consistent shape language across the app.
abstract final class AppRadius {
  /// Extra small radius (4dp).
  static const double xs = 4;

  /// Small radius (8dp).
  static const double sm = 8;

  /// Medium radius (12dp).
  static const double md = 12;

  /// Large radius (16dp).
  static const double lg = 16;

  /// Extra large radius (20dp).
  static const double xl = 20;

  /// Double extra large radius (24dp).
  static const double xxl = 24;

  /// Triple extra large radius (32dp).
  static const double xxxl = 32;

  /// Fully rounded/circular radius (9999dp).
  static const double full = 9999;

  /// Standard card radius.
  static const double card = lg;

  /// Standard button radius.
  static const double button = md;

  /// Standard chip/badge radius.
  static const double chip = sm;

  /// Standard dialog/sheet radius.
  static const double dialog = xxl;

  /// Standard bottom sheet top radius.
  static const double bottomSheet = xxxl;
}
